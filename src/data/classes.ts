export function normalizeCharacterClassId(raw: string): CharacterClassId {
  if (raw === 'warrior' || raw === 'mage' || raw === 'assassin') {
    return raw;
  }
  if (raw === 'valkyrie') return 'warrior';
  if (raw === 'astral_weaver') return 'mage';
  return 'assassin';
}

