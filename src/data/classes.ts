export function computeEffectiveStats(character: CharacterSaveData): CharacterStats {
  const levelBonusMultiplier = 1 + (character.level - 1) * 0.12;
  const weapon = character.equipped.weapon;
  const charm = character.equipped.charm;

  const bonusAttack = (weapon?.attackBonus ?? 0) + (charm?.attackBonus ?? 0);
  const bonusHp = (weapon?.maxHpBonus ?? 0) + (charm?.maxHpBonus ?? 0);
  const bonusCrit = (weapon?.critRateBonus ?? 0) + (charm?.critRateBonus ?? 0);

  return {
    maxHp: Math.round(character.baseStats.maxHp * levelBonusMultiplier + bonusHp),
    attack: Math.round(character.baseStats.attack * levelBonusMultiplier + bonusAttack),
    defense: Math.round(character.baseStats.defense * levelBonusMultiplier),
    critRate: Math.min(0.85, Number((character.baseStats.critRate + bonusCrit).toFixed(3))),
    critDamage: Number((character.baseStats.critDamage + (character.level - 1) * 0.03).toFixed(2)),
    moveSpeed: character.baseStats.moveSpeed,
    attackSpeed: character.baseStats.attackSpeed,
  };
}

export function computePowerRating(character: CharacterSaveData): number {
  const stats = computeEffectiveStats(character);
  const skillSum =
    character.skillLevels.basic +
    character.skillLevels.skill1 +
    character.skillLevels.skill2 +
    character.skillLevels.ultimate;
  return Math.round(
    stats.attack * 6.5 +
      stats.maxHp * 0.45 +
      stats.defense * 4 +
      stats.critRate * 400 +
      skillSum * 35
  );
}
